declare(strict_types=1);

$root = dirname(__DIR__);
$target = $root . '/.env';

/**
 * @param array<string, string> $defaults
 */
function environmentValue(string $key, array $defaults): ?string
{
    $value = getenv($key);

    if (is_string($value) && $value !== '') {
        return $value;
    }

    return $defaults[$key] ?? null;
}

function assertEnvValue(string $key, string $value): void
{
    if (strpbrk($value, "\r\n\"'\\") !== false) {
        fwrite(STDERR, "Environment value for {$key} contains a character that cannot be written to .env.\n");
        exit(1);
    }
}

$defaults = [
    'APP_NAME' => 'Work Schedule Manager',
    'APP_VERSION' => '1.0.0',
    'APP_DEBUG' => 'false',
    'APP_LOCALE' => 'lv',
    'APP_FALLBACK_LOCALE' => 'lv',
    'SESSION_NAME' => 'work_schedule_manager_session',
    'DB_PORT' => '3306',
    'DB_CHARSET' => 'utf8mb4',
    'EMAIL_NOTIFICATIONS_ENABLED' => 'false',
    'EMAIL_FROM_ADDRESS' => 'noreply@example.com',
    'EMAIL_FROM_NAME' => 'Work Schedule Manager',
    'EMAIL_REPLY_TO' => '',
];

$required = [
    'APP_URL',
    'DB_HOST',
    'DB_DATABASE',
    'DB_USERNAME',
    'DB_PASSWORD',
];

$optional = [
    'APP_NAME',
    'APP_VERSION',
    'APP_DEBUG',
    'APP_LOCALE',
    'APP_FALLBACK_LOCALE',
    'SESSION_NAME',
    'SESSION_SECURE_COOKIE',
    'DB_PORT',
    'DB_CHARSET',
    'EMAIL_NOTIFICATIONS_ENABLED',
    'EMAIL_FROM_ADDRESS',
    'EMAIL_FROM_NAME',
    'EMAIL_REPLY_TO',
];

$lines = [
    '# Generated at container start from the process environment.',
    '# Do not edit this file inside the container; change the Coolify variables and redeploy.',
    '',
];

foreach (array_merge($required, $optional) as $key) {
    $value = environmentValue($key, $defaults);

    if ($value === null) {
        if (in_array($key, $required, true)) {
            fwrite(STDERR, "Missing required environment variable {$key}.\n");
            exit(1);
        }

        continue;
    }

    assertEnvValue($key, $value);
    $lines[] = $key . '="' . $value . '"';
}

$temporary = $target . '.tmp';
$written = file_put_contents(
    $temporary,
    implode("\n", $lines) . "\n",
    LOCK_EX
);

if ($written === false) {
    fwrite(STDERR, "Unable to write {$temporary}.\n");
    exit(1);
}

if (!rename($temporary, $target)) {
    fwrite(STDERR, "Unable to replace {$target}.\n");
    exit(1);
}

fwrite(STDOUT, "Wrote .env from the container environment.\n");
